def _walk_find(pred, root="/kaggle/input", max_depth=7):
    base = len(Path(root).parts)
    for r, dirs, files in os.walk(root):
        hit = pred(Path(r), files)
        if hit:
            return hit
        dirs[:] = [] if len(Path(r).parts) - base >= max_depth else \
            [d for d in dirs if not d.startswith(("images", "labels", "label_2")) and d not in SPLITS]


