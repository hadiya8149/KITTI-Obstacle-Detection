def iou_matrix(a, b):
    """IoU between boxes a (N,4) and b (M,4) in x1,y1,x2,y2."""
    if len(a) == 0 or len(b) == 0:
        return np.zeros((len(a), len(b)))
    ix1 = np.maximum(a[:, None, 0], b[None, :, 0]); iy1 = np.maximum(a[:, None, 1], b[None, :, 1])
    ix2 = np.minimum(a[:, None, 2], b[None, :, 2]); iy2 = np.minimum(a[:, None, 3], b[None, :, 3])
    inter = np.clip(ix2 - ix1, 0, None) * np.clip(iy2 - iy1, 0, None)
    area_a = (a[:, 2] - a[:, 0]) * (a[:, 3] - a[:, 1])
    area_b = (b[:, 2] - b[:, 0]) * (b[:, 3] - b[:, 1])
    return inter / (area_a[:, None] + area_b[None, :] - inter + 1e-9)


def inside_fraction(dets, regions):
    """Fraction of each detection's area covered by its most-overlapping DontCare region."""
    if len(dets) == 0 or len(regions) == 0:
        return np.zeros(len(dets))
    ix1 = np.maximum(dets[:, None, 0], regions[None, :, 0]); iy1 = np.maximum(dets[:, None, 1], regions[None, :, 1])
    ix2 = np.minimum(dets[:, None, 2], regions[None, :, 2]); iy2 = np.minimum(dets[:, None, 3], regions[None, :, 3])
    inter = np.clip(ix2 - ix1, 0, None) * np.clip(iy2 - iy1, 0, None)
    area = (dets[:, 2] - dets[:, 0]) * (dets[:, 3] - dets[:, 1])
    return (inter / (area[:, None] + 1e-9)).max(axis=1)


def ap_r40(scores, tp, n_pos):
    """KITTI 40-recall-point interpolated AP, plus the precision / recall curve."""
    if n_pos == 0:
        return np.nan, np.array([]), np.array([])
    if len(scores) == 0:
        return 0.0, np.array([0.0]), np.array([0.0])
    order = np.argsort(-scores, kind="stable")
    tp = tp[order]
    ctp, cfp = np.cumsum(tp), np.cumsum(1 - tp)
    rec = ctp / n_pos
    prec = ctp / np.maximum(ctp + cfp, 1e-9)
    env = np.maximum.accumulate(prec[::-1])[::-1]
    idx = np.searchsorted(rec, R40, side="left")
    ap = np.where(idx < len(env), env[np.minimum(idx, len(env) - 1)], 0.0).mean()
    return float(ap), prec, rec


def _pack_preds(preds):
    p = preds[preds["type"].isin(CIDX)]
    return {k: (g[["x1", "y1", "x2", "y2"]].to_numpy(float), g["type"].map(CIDX).to_numpy(int),
                g["score"].to_numpy(float)) for k, g in p.groupby("image_id")}


class Evaluator:
    """Build once per image set (ground truth indexed per image), then score any set of predictions."""

    def __init__(self, ann, ignore_regions, image_ids):
        self.image_ids = [str(i).zfill(6) for i in image_ids]
        ids = set(self.image_ids)
        ann = ann[ann["image_id"].isin(ids)]
        ign = ignore_regions[ignore_regions["image_id"].isin(ids)]
        self.gt = {k: (g[["x1", "y1", "x2", "y2"]].to_numpy(float), g["type"].map(CIDX).to_numpy(int),
                       g["occluded"].to_numpy(int), g["truncated"].to_numpy(float)) for k, g in ann.groupby("image_id")}
        self.dc = {k: g[["x1", "y1", "x2", "y2"]].to_numpy(float) for k, g in ign.groupby("image_id")}

    def _gt_for(self, image_id, ci, diff):
        g = self.gt.get(image_id)
        if g is None:
            return np.zeros((0, 4)), np.zeros(0, bool)
        boxes, cls, occ, trunc = g
        min_h, max_occ, max_trunc = DIFFICULTY[diff]
        same = cls == ci
        neigh = np.isin(cls, [CIDX[n] for n in NEIGHBOUR.get(CLASSES[ci], [])])
        h = boxes[:, 3] - boxes[:, 1]
        valid = same & (h >= min_h) & (occ <= max_occ) & (trunc <= max_trunc)
        keep = same | neigh
        return boxes[keep], valid[keep]

    def match_class(self, packed, cls, diff="moderate", iou_thr=0.5):
        """Scores and TP flags of the non-ignored detections of one class, and the number of valid GT objects."""
        ci, min_h = CIDX[cls], DIFFICULTY[diff][0]
        all_scores, all_tp, n_pos = [], [], 0
        empty = np.zeros((0, 4))
        for image_id in self.image_ids:
            gt_boxes, is_valid = self._gt_for(image_id, ci, diff)
            n_pos += int(is_valid.sum())
            p = packed.get(image_id)
            if p is None:
                continue
            m = p[1] == ci
            if not m.any():
                continue
            boxes, scores = p[0][m], p[2][m]
            o = np.argsort(-scores, kind="stable")
            boxes, scores = boxes[o], scores[o]
            ious = iou_matrix(boxes, gt_boxes)
            dc_frac = inside_fraction(boxes, self.dc.get(image_id, empty))
            small = (boxes[:, 3] - boxes[:, 1]) < min_h
            used = np.zeros(len(gt_boxes), bool)
            for j in range(len(boxes)):
                if len(gt_boxes):
                    hit = ious[j] >= iou_thr
                    cand = np.flatnonzero(is_valid & ~used & hit)
                    if len(cand):
                        used[cand[np.argmax(ious[j, cand])]] = True
                        all_scores.append(scores[j]); all_tp.append(1.0)
                        continue
                    if (~is_valid & hit).any():
                        continue                                   # matched an ignored object
                if small[j] or dc_frac[j] >= 0.5:
                    continue                                       # too small for this difficulty / in DontCare
                all_scores.append(scores[j]); all_tp.append(0.0)   # false positive
        return np.array(all_scores, float), np.array(all_tp, float), n_pos

    def evaluate(self, preds, classes=CLASSES, difficulties=("easy", "moderate", "hard", "all"),
                 iou_thrs=(0.5,), op_conf=0.25, packed=None):
        """One row per (class, difficulty, IoU): AP, #GT, recall / precision at the operating threshold."""
        packed = packed if packed is not None else _pack_preds(preds)
        rows = []
        for cls in classes:
            for diff in difficulties:
                for thr in iou_thrs:
                    s, tp, n_pos = self.match_class(packed, cls, diff, thr)
                    ap, prec, rec = ap_r40(s, tp, n_pos)
                    keep = s >= op_conf
                    rows.append({"class": cls, "difficulty": diff, "iou": round(float(thr), 2), "AP": ap,
                                 "n_gt": n_pos, "n_det": len(s),
                                 "recall_max": float(rec.max()) if (len(rec) and n_pos) else np.nan,
                                 "recall_op": float(tp[keep].sum() / n_pos) if n_pos else np.nan,
                                 "precision_op": float(tp[keep].mean()) if keep.any() else np.nan})
        return pd.DataFrame(rows)

    def pr_curve(self, preds, cls, diff="moderate", iou_thr=0.5):
        s, tp, n_pos = self.match_class(_pack_preds(preds), cls, diff, iou_thr)
        return ap_r40(s, tp, n_pos)

    def summary(self, preds, with_coco_range=True):
        """Headline numbers (dict) and the full per-class table."""
        packed = _pack_preds(preds)
        t = self.evaluate(preds, iou_thrs=(0.5, 0.7), packed=packed)
        a50 = t[t.iou == 0.5].set_index(["class", "difficulty"])
        a70 = t[t.iou == 0.7].set_index(["class", "difficulty"])
        out = {}
        for c in FOCUS:
            for d in ["easy", "moderate", "hard"]:
                out[f"AP50_{c}_{d}"] = a50.loc[(c, d), "AP"]
            out[f"recall_{c}_mod"] = a50.loc[(c, "moderate"), "recall_op"]
        out["primary_mAP50_mod"] = np.nanmean([out[f"AP50_{c}_moderate"] for c in FOCUS])
        out["mAP50_easy"] = np.nanmean([out[f"AP50_{c}_easy"] for c in FOCUS])
        out["mAP50_hard"] = np.nanmean([out[f"AP50_{c}_hard"] for c in FOCUS])
        out["mAP50_all8"] = np.nanmean([a50.loc[(c, "all"), "AP"] for c in CLASSES])
        out["AP70_Car_mod"] = a70.loc[("Car", "moderate"), "AP"]
        if with_coco_range:
            thr = np.round(np.arange(0.5, 0.96, 0.05), 2)
            r = self.evaluate(preds, difficulties=("all",), iou_thrs=thr, packed=packed)
            out["mAP50_95_all8"] = float(r.groupby("iou")["AP"].mean().mean())
        return {k: float(v) for k, v in out.items()}, t


def gt_as_predictions(ann, image_ids):
    """Sanity check: the ground truth fed back as predictions must score AP = 1."""
    g = ann[ann["image_id"].isin(set(image_ids))][["image_id", "type", "x1", "y1", "x2", "y2"]].copy()
    g["score"] = 1.0
    return g


