COLUMNS = ["image_id", "type", "x1", "y1", "x2", "y2", "score"]


def yolo_predict(model, paths, imgsz=640, conf=0.001, iou=0.6, half=True, max_det=100, class_map=None,
                 batch=16, desc="predict"):
    """model: ultralytics.YOLO or a weights path. class_map: {model class id: KITTI name} (COCO baseline only)."""
    from ultralytics import YOLO
    if not hasattr(model, "predict"):
        model = YOLO(str(model))
    half = half and torch.cuda.is_available()
    rows, paths = [], [str(p) for p in paths]
    for i in tqdm(range(0, len(paths), batch), desc=desc):
        for r in model.predict(paths[i:i + batch], imgsz=imgsz, conf=conf, iou=iou,
                               quantize="fp16" if half else None, max_det=max_det, verbose=False):
            b = r.boxes
            if b is None or len(b) == 0:
                continue
            xyxy, sc, cl = b.xyxy.cpu().numpy(), b.conf.cpu().numpy(), b.cls.cpu().numpy().astype(int)
            img_id = Path(r.path).stem
            for (x1, y1, x2, y2), s, c in zip(xyxy, sc, cl):
                name = class_map.get(c) if class_map is not None else CLASSES[c]
                if name is not None:
                    rows.append((img_id, name, x1, y1, x2, y2, s))
    return pd.DataFrame(rows, columns=COLUMNS)


def build_frcnn(pretrained=True, score_thresh=0.001, detections_per_img=100):
    """torchvision Faster R-CNN (ResNet-50 FPN, COCO weights) with a new box head for 8 classes + background."""
    from torchvision.models import detection as D
    from torchvision.models.detection.faster_rcnn import FastRCNNPredictor
    m = D.fasterrcnn_resnet50_fpn(weights="DEFAULT" if pretrained else None, box_score_thresh=score_thresh,
                                  box_detections_per_img=detections_per_img)
    m.roi_heads.box_predictor = FastRCNNPredictor(m.roi_heads.box_predictor.cls_score.in_features, len(CLASSES) + 1)
    return m


def load_frcnn(weights, device=None):
    ckpt = torch.load(weights, map_location="cpu", weights_only=False)
    m = build_frcnn(pretrained=False)
    m.load_state_dict(ckpt["model"] if "model" in ckpt else ckpt)
    return m.to(device or ("cuda" if torch.cuda.is_available() else "cpu")).eval()


def read_rgb(path):
    from torchvision.io import read_image, ImageReadMode
    return read_image(str(path), ImageReadMode.RGB).float() / 255.0


@torch.no_grad()
def frcnn_predict(model, paths, batch=8, half=True, desc="predict"):
    if not hasattr(model, "roi_heads"):
        model = load_frcnn(model)
    device = next(model.parameters()).device
    amp = half and device.type == "cuda"
    rows, paths = [], [Path(p) for p in paths]
    for i in tqdm(range(0, len(paths), batch), desc=desc):
        chunk = paths[i:i + batch]
        with torch.autocast("cuda", dtype=torch.float16, enabled=amp):
            out = model([read_rgb(p).to(device) for p in chunk])
        for p, o in zip(chunk, out):
            for (x1, y1, x2, y2), s, l in zip(o["boxes"].float().cpu().numpy(), o["scores"].float().cpu().numpy(),
                                              o["labels"].cpu().numpy()):
                if l >= 1:
                    rows.append((p.stem, CLASSES[l - 1], x1, y1, x2, y2, s))
    return pd.DataFrame(rows, columns=COLUMNS)


def predict(kind, weights, paths, imgsz=640, class_map=None, desc="predict"):
    """kind = 'yolo' | 'frcnn'."""
    if kind == "frcnn":
        return frcnn_predict(weights, paths, desc=desc)
    return yolo_predict(weights, paths, imgsz=imgsz, class_map=class_map, desc=desc)


def repeat_factors(ann_train, train_ids, t=0.3):
    presence = (pd.crosstab(ann_train["image_id"], ann_train["type"])
                  .reindex(index=train_ids, columns=CLASSES, fill_value=0) > 0)
    img_frac = presence.mean(axis=0)
    class_r = np.maximum(1.0, np.sqrt(t / img_frac.clip(lower=1e-12)))
    img_r = (presence * class_r).max(axis=1).clip(lower=1.0)
    return img_r, pd.DataFrame({"img_fraction": img_frac, "class_repeat": class_r})


def write_rfs_list(tables, root=DATA, kind="grouped", name="train_rfs.txt"):
    """Oversampled training list + its YOLO yaml. Returns (yaml path, per-class table, images per epoch)."""
    images, ann, _ = tables
    tr = split_ids(images, "train", kind)
    img_r, table = repeat_factors(ann[ann.image_id.isin(set(tr))], tr)
    rng = np.random.default_rng(SEED)
    reps = np.floor(img_r.values).astype(int) + (rng.random(len(img_r)) < img_r.values % 1).astype(int)
    paths = image_paths(img_r.index, images=images) if kind == "random" else         image_paths(img_r.index, img_dir=Path(root) / "images" / "train")
    lines = [os.path.abspath(p) for p, k in zip(paths, reps) for _ in range(k)]
    rng.shuffle(lines)
    (Path(root) / name).write_text("\n".join(lines) + "\n")
    val = "random_val.txt" if kind == "random" else "images/val"
    test = "random_test.txt" if kind == "random" else "images/test"
    y = write_yaml(root, train=name, val=val, test=test, name=name.replace(".txt", ".yaml"))
    print(f"RFS: {len(tr)} training images -> {len(lines)} per epoch")
    return y, table, len(lines)


WEATHER = ["fog", "rain", "low_light"]
SEVERITIES = [1, 2, 3]


def _rng(image_id, kind, severity):
    return np.random.default_rng(zlib.crc32(f"{image_id}|{kind}|{severity}|0".encode()))


def _fog(img, severity, rng):
    import cv2
    beta = [0.9, 1.6, 2.6][severity - 1]
    h, w = img.shape[:2]
    y = np.linspace(0, 1, h)[:, None]
    depth = np.clip(1.0 - 1.6 * np.clip(y - 0.45, 0, None), 0.25, 1.0) * np.ones((1, w))
    noise = cv2.GaussianBlur(rng.normal(0, 1, (h // 8 + 1, w // 8 + 1)).astype(np.float32), (0, 0), 3)
    noise = cv2.resize(noise, (w, h)) * 0.12
    t = np.exp(-beta * np.clip(depth + noise, 0.1, 1.2))[..., None]
    out = img.astype(np.float32) / 255.0 * t + rng.uniform(0.78, 0.88) * (1 - t)
    return np.clip(out * 255, 0, 255).astype(np.uint8)


def _rain(img, severity, rng):
    import cv2
    n, length, dim = [400, 1100, 2400][severity - 1], [10, 16, 24][severity - 1], [0.88, 0.78, 0.68][severity - 1]
    h, w = img.shape[:2]
    angle = np.deg2rad(rng.uniform(-15, 15))
    layer = np.zeros((h, w), np.float32)
    dx, dy = int(length * np.sin(angle)), int(length * np.cos(angle))
    for x, y_ in zip(rng.integers(0, w, n), rng.integers(0, h, n)):
        cv2.line(layer, (int(x), int(y_)), (int(x + dx), int(y_ + dy)), float(rng.uniform(0.5, 1.0)), 1)
    layer = cv2.blur(layer, (3, 3))[..., None]
    base = cv2.GaussianBlur(img, (0, 0), [0.6, 1.0, 1.4][severity - 1]).astype(np.float32) * dim
    return np.clip(base * (1 - 0.6 * layer) + 210 * 0.6 * layer, 0, 255).astype(np.uint8)


def _low_light(img, severity, rng):
    gamma, gain, sigma = [1.6, 2.1, 2.6][severity - 1], [0.55, 0.38, 0.25][severity - 1], [0.012, 0.022, 0.035][severity - 1]
    x = (img.astype(np.float32) / 255.0) ** gamma * gain
    x = x + rng.normal(0, 1, x.shape).astype(np.float32) * (sigma + 0.5 * sigma * np.sqrt(x))
    return np.clip(x * 255, 0, 255).astype(np.uint8)


def corrupt(img_bgr, kind, severity, image_id="0"):
    """Deterministic test-time corruption of one BGR image (severity 0 = unchanged)."""
    if severity == 0:
        return img_bgr
    return {"fog": _fog, "rain": _rain, "low_light": _low_light}[kind](img_bgr, severity, _rng(image_id, kind, severity))


def build_corrupted_test(ids, out_root=None):
    """DATA/corrupted/<kind>_s<severity>/<id>.png for every test image."""
    import cv2
    out_root = Path(out_root or DATA / "corrupted")

    def one(job):
        kind, s, i = job
        dst = out_root / f"{kind}_s{s}" / f"{i}.png"
        if not dst.exists():
            img = cv2.imread(str(DATA / "images" / "test" / f"{i}.png"))
            cv2.imwrite(str(dst), corrupt(img, kind, s, i), [cv2.IMWRITE_PNG_COMPRESSION, 1])

    jobs = [(k, s, i) for k in WEATHER for s in SEVERITIES for i in ids]
    for k in WEATHER:
        for s in SEVERITIES:
            (out_root / f"{k}_s{s}").mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(8) as ex:
        list(tqdm(ex.map(one, jobs), total=len(jobs), desc="corrupted test sets"))
    return out_root


def weather_train_transform():
    import albumentations as A
    return A.OneOf([
        A.RandomFog(fog_coef_range=(0.2, 0.6), alpha_coef=0.08, p=1.0),
        A.RandomRain(slant_range=(-12, 12), drop_length=18, blur_value=5, brightness_coefficient=0.75,
                     rain_type="drizzle", p=1.0),
        A.Compose([A.RandomGamma(gamma_limit=(150, 260), p=1.0),
                   A.RandomBrightnessContrast(brightness_limit=(-0.45, -0.2), contrast_limit=(-0.2, 0.0), p=1.0),
                   A.GaussNoise(std_range=(0.02, 0.06), p=1.0)], p=1.0),
    ], p=1.0)


def build_weather_train_set(train_ids, fraction=0.5, out=None):
    """Copy of the grouped YOLO dataset in which `fraction` of the TRAIN images are weather-augmented.
    Validation and test stay clean; labels are shared."""
    import cv2
    out = Path(out or DATA.parent / "kitti_weather")
    random.seed(SEED); np.random.seed(SEED)
    chosen = set(np.random.default_rng(SEED).choice(train_ids, int(len(train_ids) * fraction), replace=False))
    tf = weather_train_transform()
    (out / "images" / "train").mkdir(parents=True, exist_ok=True)
    (out / "labels").mkdir(parents=True, exist_ok=True)
    for s in SPLITS:
        if not (out / "labels" / s).exists():
            shutil.copytree(DATA / "labels" / s, out / "labels" / s)
        if s != "train" and not (out / "images" / s).exists():
            os.symlink((DATA / "images" / s).resolve(), out / "images" / s, target_is_directory=True)
    for i in tqdm(train_ids, desc="weather-augmented train set"):
        src, dst = DATA / "images" / "train" / f"{i}.png", out / "images" / "train" / f"{i}.png"
        if dst.exists() or dst.is_symlink():
            continue
        if i in chosen:
            img = cv2.cvtColor(cv2.imread(str(src)), cv2.COLOR_BGR2RGB)
            cv2.imwrite(str(dst), cv2.cvtColor(tf(image=img)["image"], cv2.COLOR_RGB2BGR), [cv2.IMWRITE_PNG_COMPRESSION, 1])
        else:
            os.symlink(src.resolve(), dst)
    return out, sorted(chosen)


