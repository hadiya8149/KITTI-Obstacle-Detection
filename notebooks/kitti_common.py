class KittiDetDataset(torch.utils.data.Dataset):
    """Images + boxes for Faster R-CNN (boxes in pixel corners, labels 1..8; 0 is background)."""

    def __init__(self, ids, ann, split, train=False):
        self.ids, self.split, self.train = list(ids), split, train
        g = ann[ann["image_id"].isin(set(self.ids))]
        self.boxes = {k: v[["x1", "y1", "x2", "y2"]].to_numpy(np.float32) for k, v in g.groupby("image_id")}
        self.labels = {k: v["type"].map(CLASS_TO_ID).to_numpy(np.int64) + 1 for k, v in g.groupby("image_id")}
        if train:
            from torchvision.transforms import ColorJitter
            self.jitter = ColorJitter(brightness=0.3, contrast=0.3, saturation=0.3, hue=0.02)

    def __len__(self):
        return len(self.ids)

    def __getitem__(self, i):
        iid = self.ids[i]
        img = read_rgb(DATA / "images" / self.split / f"{iid}.png")
        h, w = img.shape[1:]
        boxes = torch.from_numpy(self.boxes.get(iid, np.zeros((0, 4), np.float32)).copy())
        labels = torch.from_numpy(self.labels.get(iid, np.zeros(0, np.int64)).copy())
        boxes[:, 0::2] = boxes[:, 0::2].clamp(0, w)
        boxes[:, 1::2] = boxes[:, 1::2].clamp(0, h)
        keep = (boxes[:, 2] > boxes[:, 0] + 1) & (boxes[:, 3] > boxes[:, 1] + 1)
        boxes, labels = boxes[keep], labels[keep]
        if self.train:
            if torch.rand(1).item() < 0.5:
                img = img.flip(-1)
                boxes = boxes[:, [2, 1, 0, 3]] * torch.tensor([-1, 1, -1, 1]) + torch.tensor([w, 0, w, 0])
            img = self.jitter(img)
        return img, {"boxes": boxes, "labels": labels}


def _collate(batch):
    return tuple(zip(*batch))


def train_frcnn(exp_id, tables, epochs=10, batch=4, lr=0.01, workers=4):
    """Returns (weights, info dict); writes results/<exp_id>/history.csv after every epoch."""
    seed_everything()
    images, ann, ign = tables
    device = "cuda" if torch.cuda.is_available() else "cpu"
    tr, va = split_ids(images, "train"), split_ids(images, "val")
    if SMOKE:
        tr, epochs = tr[:200], 2
    dl = torch.utils.data.DataLoader(KittiDetDataset(tr, ann, "train", train=True), batch_size=batch, shuffle=True,
                                     num_workers=workers, collate_fn=_collate, persistent_workers=workers > 0,
                                     generator=torch.Generator().manual_seed(SEED))
    dl_val = torch.utils.data.DataLoader(KittiDetDataset(va, ann, "val"), batch_size=batch, num_workers=workers,
                                         collate_fn=_collate)
    model = build_frcnn().to(device)
    opt = torch.optim.SGD([p for p in model.parameters() if p.requires_grad], lr=lr, momentum=0.9, weight_decay=1e-4)
    iters, warm = len(dl) * epochs, min(500, len(dl))
    milestones = [int(0.7 * iters), int(0.9 * iters)]
    sched = torch.optim.lr_scheduler.LambdaLR(opt, lambda it: min(1.0, (it + 1) / warm) * 0.1 ** sum(it >= m for m in milestones))
    scaler = torch.amp.GradScaler("cuda", enabled=device == "cuda")
    evaluator = Evaluator(ann, ign, va)
    va_paths = image_paths(va, "val")
    d, out_w = exp_dir(exp_id), WEIGHTS / f"{exp_id}.pt"
    WEIGHTS.mkdir(parents=True, exist_ok=True)
    history, best, t0 = [], -1.0, time.time()
    for ep in range(1, epochs + 1):
        model.train()
        sums = {}
        for imgs, tg in tqdm(dl, desc=f"epoch {ep}/{epochs} train"):
            imgs = [im.to(device, non_blocking=True) for im in imgs]
            tg = [{k: v.to(device) for k, v in t.items()} for t in tg]
            with torch.autocast("cuda", dtype=torch.float16, enabled=device == "cuda"):
                parts = model(imgs, tg)
                loss = sum(parts.values())
            opt.zero_grad(set_to_none=True)
            scaler.scale(loss).backward()
            scaler.step(opt); scaler.update(); sched.step()
            for k, v in parts.items():
                sums[k] = sums.get(k, 0.0) + v.item()
        row = {"epoch": ep, **{f"train/{k}": v / len(dl) for k, v in sums.items()}}
        row["train/loss"] = sum(v for k, v in row.items() if k.startswith("train/loss_"))
        vsums = {}                                       # validation loss: train-mode forward, no gradient
        with torch.no_grad():
            for imgs, tg in tqdm(dl_val, desc=f"epoch {ep}/{epochs} val loss", leave=False):
                imgs = [im.to(device) for im in imgs]
                tg = [{k: v.to(device) for k, v in t.items()} for t in tg]
                with torch.autocast("cuda", dtype=torch.float16, enabled=device == "cuda"):
                    for k, v in model(imgs, tg).items():
                        vsums[k] = vsums.get(k, 0.0) + v.item()
        row.update({f"val/{k}": v / len(dl_val) for k, v in vsums.items()})
        row["val/loss"] = sum(v for k, v in row.items() if k.startswith("val/loss_"))
        model.eval()
        s, _ = evaluator.summary(frcnn_predict(model, va_paths, desc=f"epoch {ep}/{epochs} val mAP"), with_coco_range=False)
        row.update({"val/primary_mAP50_mod": s["primary_mAP50_mod"], "val/mAP50_all8": s["mAP50_all8"],
                    "lr": opt.param_groups[0]["lr"], "elapsed_h": (time.time() - t0) / 3600})
        if s["primary_mAP50_mod"] > best:
            best = s["primary_mAP50_mod"]
            torch.save({"model": model.state_dict(), "epoch": ep}, out_w)
        history.append(row)
        pd.DataFrame(history).to_csv(d / "history.csv", index=False)
        print(f"epoch {ep}: train loss {row['train/loss']:.3f} | val loss {row['val/loss']:.3f} | "
              f"val primary {row['val/primary_mAP50_mod']:.3f}")
    hist = pd.DataFrame(history)
    info = {"model": "fasterrcnn_resnet50_fpn (COCO)", "imgsz": "800/1333", "batch": batch, "max_epochs": epochs,
            "epochs_run": epochs, "best_epoch": int(hist.loc[hist["val/primary_mAP50_mod"].idxmax(), "epoch"]),
            "train_hours": round((time.time() - t0) / 3600, 3),
            "settings": json.dumps({"optimizer": "SGD", "lr": lr, "amp": True})}
    return out_w, info


