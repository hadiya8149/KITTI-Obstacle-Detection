def _copy_files(src, dst, workers=64):
    dst.mkdir(parents=True, exist_ok=True)
    entries = [e for e in os.scandir(src) if e.is_file()]
    cp = lambda e: (dst / e.name).exists() or shutil.copyfile(e.path, dst / e.name)
    with ThreadPoolExecutor(workers) as ex:
        list(tqdm(ex.map(cp, entries), total=len(entries), desc=f"copy {src.parent.name}/{src.name}", leave=False))


def _fetch_split(ds, kind, split):
    """Make DATA/<kind>/<split>/ exist (kind = images | labels) from a folder or a zip in the dataset."""
    dst = DATA / kind / split
    if dst.is_dir() and any(dst.iterdir()):
        return dst
    folders = [ds / f"{kind}_{split}" / kind / split, ds / f"{kind}_yolo" / kind / split, ds / kind / split]
    zips = [ds / f"{kind}_{split}.zip", ds / f"{kind}_yolo.zip"]
    for f in folders:
        if f.is_dir() and f.resolve() != dst.resolve():
            _copy_files(f, dst)
            return dst
    for z in zips:
        if z.exists():
            with zipfile.ZipFile(z) as zf:
                members = [m for m in zf.namelist() if m.startswith(f"{kind}/{split}/")]
                for m in tqdm(members, desc=f"unzip {z.name} ({split})", leave=False):
                    zf.extract(m, DATA)
            return dst
    raise FileNotFoundError(f"{kind}/{split} not found in {ds}")


